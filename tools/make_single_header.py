#!/usr/bin/env python3
"""Generate single_header/lcd_gfx.h, the stb-style single-header build.

The header holds the declarations of every module. The implementation is
compiled only in the translation unit that defines GFX_IMPLEMENTATION before
including it.

Usage:
    python3 tools/make_single_header.py            write single_header/lcd_gfx.h
    python3 tools/make_single_header.py --check    exit 1 if the committed file is stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, 'include')
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, 'single_header', 'lcd_gfx.h')

# (module, macro that removes it from the build, or None)
MODULES = [
    ('core', None), ('shapes', None), ('text', None), ('image', None),
    ('fonts', None), ('icons', None), ('widgets', None),
    ('selftest', 'GFX_WITHOUT_SELFTEST'),
    ('sample_scene', 'GFX_WITHOUT_DEMO'), ('sample_smile', 'GFX_WITHOUT_DEMO'),
    ('demo', 'GFX_WITHOUT_DEMO'),
]
# gfx_port.h is declared once at the top of the declarations.
PORT = 'port'

CPLUSPLUS_OPEN = re.compile(r'#ifdef __cplusplus\nextern "C" \{\n#endif\n?')
CPLUSPLUS_CLOSE = re.compile(r'#ifdef __cplusplus\n\}\n#endif\n?')
GFX_INCLUDE = re.compile(r'^#include "gfx_[a-z_0-9]+\.h"[ \t]*\n', re.M)
SYS_INCLUDE = re.compile(r'^#include <[a-z_0-9.]+>[ \t]*\n', re.M)


def read(path):
    with open(path, encoding='utf-8', newline='') as f:
        return f.read().replace('\r\n', '\n')


def split_header(text):
    """Return (leading comment, body) of a header, without its include guard."""
    m = re.search(r'#ifndef (\w+)\n#define \1\n', text)
    lead = text[:m.start()].strip('\n')
    body = text[m.end():]
    body = body[:body.rstrip().rfind('#endif')]
    body = CPLUSPLUS_OPEN.sub('', body)
    body = CPLUSPLUS_CLOSE.sub('', body)
    body = GFX_INCLUDE.sub('', body)
    body = SYS_INCLUDE.sub('', body)
    return lead, body.strip('\n')


def wrap(macro, text):
    if not macro:
        return text
    return '#ifndef %s\n%s\n#endif /* !%s */' % (macro, text, macro)


BANNER = '''/*
 * lcd_gfx.h - stm32-st7789-gfx as a single header (stb style)
 * https://github.com/JuanP-G/stm32-st7789-gfx
 *
 * Portable C99 graphics for ST7789 panels (240 x 240, RGB565) driven through
 * two functions: gfx_port_cmd() and gfx_port_data(). Integer arithmetic only.
 *
 * USAGE
 *   In every file that draws:
 *       #include "lcd_gfx.h"
 *   In exactly ONE .c file, before the include:
 *       #define GFX_IMPLEMENTATION
 *       #include "lcd_gfx.h"
 *   Then implement the two port functions once (see gfx_port_cmd below).
 *
 * OPTIONS (define before the include, in the file that defines GFX_IMPLEMENTATION
 * and in every file that includes the header, to keep both sides in sync)
 *   GFX_WITHOUT_DEMO       leave out the demo pages and their sample images
 *   GFX_WITHOUT_SELFTEST   leave out the board self-test patterns
 *
 * Generated by tools/make_single_header.py from include/ and src/.
 * Do not edit by hand: edit the sources and regenerate.
 *
 * LICENSE: MIT. The bundled fonts are derived from DejaVu Sans; see
 * THIRD_PARTY_NOTICES.md in the repository.
 */'''


def build():
    parts = [BANNER, '#ifndef LCD_GFX_H_', '#define LCD_GFX_H_', '',
             '#include <stdint.h>', '#include <stddef.h>', '',
             '#ifdef __cplusplus', 'extern "C" {', '#endif', '']
    # ---- declarations ----
    lead, body = split_header(read(os.path.join(INC, 'gfx_%s.h' % PORT)))
    parts.append('/* ===== port ===== */\n' + lead + '\n' + body + '\n')
    for name, macro in MODULES:
        path = os.path.join(INC, 'gfx_%s.h' % name)
        lead, body = split_header(read(path))
        text = '/* ===== %s ===== */\n' % name
        if lead.startswith('/**'):
            text += lead + '\n'
        text += body + '\n'
        parts.append(wrap(macro, text))
    parts += ['#ifdef __cplusplus', '}', '#endif', '', '#endif /* LCD_GFX_H_ */', '']

    # ---- implementation ----
    impl = ['#ifdef GFX_IMPLEMENTATION', '#ifndef LCD_GFX_IMPLEMENTATION_DONE_',
            '#define LCD_GFX_IMPLEMENTATION_DONE_', '']
    for name, macro in MODULES:
        # sample data is declared in headers only; the .c files hold the arrays
        path = os.path.join(SRC, 'gfx_%s.c' % name)
        text = GFX_INCLUDE.sub('', read(path)).strip('\n')
        text = SYS_INCLUDE.sub('', text)
        impl.append(wrap(macro, '/* ===== %s: implementation ===== */\n%s\n' % (name, text)))
    impl += ['#endif /* LCD_GFX_IMPLEMENTATION_DONE_ */', '#endif /* GFX_IMPLEMENTATION */', '']
    return '\n'.join(parts + impl)


def main():
    text = build()
    if '--check' in sys.argv:
        current = read(OUT) if os.path.exists(OUT) else ''
        if current != text:
            sys.stderr.write('single_header/lcd_gfx.h is stale: run tools/make_single_header.py\n')
            return 1
        print('single_header/lcd_gfx.h is up to date')
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d bytes)' % (os.path.relpath(OUT, ROOT), len(text.encode('utf-8'))))
    return 0


if __name__ == '__main__':
    sys.exit(main())
