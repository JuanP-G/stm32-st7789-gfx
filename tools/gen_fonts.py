#!/usr/bin/env python3
"""Generate gfx_fonts.c/.h: proportional anti-aliased fonts, 4 bits per pixel.

Base font: DejaVu Sans (free Bitstream Vera / DejaVu license, see
THIRD_PARTY_NOTICES.md). Usage:

    python3 gen_fonts.py <output_dir> [<dejavu_dir>]

<dejavu_dir> is the folder holding DejaVuSans.ttf and DejaVuSans-Bold.ttf
(default: /usr/share/fonts/truetype/dejavu/). Requires Pillow.

Each font is a glyph table plus a bitmap (2 pixels per byte, high nibble on
the left). The committed src/gfx_fonts.c was produced by this script; the
output depends on the Pillow and FreeType versions, so regenerate only when
you mean to change the fonts."""
import sys, os
from PIL import Image, ImageDraw, ImageFont

DJ = '/usr/share/fonts/truetype/dejavu/'
# C name, ttf, size in px, code point ranges (inclusive)
FONTS = [
    ('sans_12',      'DejaVuSans.ttf',      12, [(32,126),(160,255)]),
    ('sans_16',      'DejaVuSans.ttf',      16, [(32,126),(160,255)]),
    ('sans_24',      'DejaVuSans.ttf',      24, [(32,126),(160,255)]),
    ('sans_bold_16', 'DejaVuSans-Bold.ttf', 16, [(32,126),(160,255)]),
    ('sans_bold_24', 'DejaVuSans-Bold.ttf', 24, [(32,126),(160,255)]),
    ('sans_bold_48', 'DejaVuSans-Bold.ttf', 48, [(32,58),(176,176)]),   # big digits: ' '..':' and the degree sign
]

def render_font(ttf, px, ranges):
    font = ImageFont.truetype(DJ+ttf, px)
    asc, desc = font.getmetrics()
    H = asc + desc
    cps = [c for a,b in ranges for c in range(a,b+1)]
    glyphs, blob = [], bytearray()
    for cp in cps:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        pad = px  # margin for negative bearings
        img = Image.new('L', (adv + 2*pad, H), 0)
        ImageDraw.Draw(img).text((pad, asc), ch, font=font, fill=255, anchor='ls')
        cols = [x for x in range(img.width) if any(img.getpixel((x,y)) > 8 for y in range(H))]
        if not cols:
            glyphs.append((len(blob), 0, adv, 0)); continue
        x0, x1 = min(cols), max(cols)
        xoff = x0 - pad
        w = x1 - x0 + 1
        if xoff < 0:                    # keep pixels inside the cell: shift the glyph
            xoff = 0
        adv = max(adv, xoff + w)
        off = len(blob)
        for y in range(H):
            row = [min(15, (img.getpixel((x0+i, y)) + 8)//17) for i in range(w)]
            if w % 2: row.append(0)
            for i in range(0, len(row), 2):
                blob.append((row[i] << 4) | row[i+1])
        glyphs.append((off, w, adv, xoff))
    assert len(blob) < 65536, (ttf, px, len(blob))
    assert all(-128 <= g[3] <= 127 and g[1] < 256 and g[2] < 256 for g in glyphs)
    return H, asc, glyphs, bytes(blob)

def main(out):
    os.makedirs(out, exist_ok=True)
    c = ['/* Generated by tools/gen_fonts.py - do not edit by hand.',
         ' * Anti-aliased 4 bpp fonts derived from DejaVu Sans (free DejaVu/Bitstream Vera license).',
         ' * See THIRD_PARTY_NOTICES.md. */',
         '#include "gfx_fonts.h"', '']
    h = ['/* Generated by tools/gen_fonts.py - do not edit by hand. */', '#ifndef GFX_FONTS_H_', '#define GFX_FONTS_H_', '',
         '#include "gfx_core.h"', '',
         '#ifdef __cplusplus', 'extern "C" {', '#endif', '',
         '/* Fonts derived from DejaVu Sans, see THIRD_PARTY_NOTICES.md. */']
    total = 0
    for name, ttf, px, rngs in FONTS:
        H, asc, glyphs, blob = render_font(ttf, px, rngs)
        total += len(blob) + 5*len(glyphs)
        c.append(f'static const uint8_t bitmap_{name}[{len(blob)}] = {{')
        for i in range(0, len(blob), 24):
            c.append('  ' + ','.join(f'0x{b:02X}' for b in blob[i:i+24]) + ',')
        c.append('};')
        c.append(f'static const gfx_glyph_t glyphs_{name}[{len(glyphs)}] = {{')
        for off, w, adv, xo in glyphs:
            c.append(f'  {{{off},{w},{adv},{xo}}},')
        c.append('};')
        # empty range: first > last
        r0, r1 = rngs[0], (rngs[1] if len(rngs) > 1 else (1, 0))
        c.append(f'const gfx_font_t gfx_font_{name} = {{glyphs_{name}, bitmap_{name}, {H}, {asc}, {r0[0]}, {r0[1]}, {r1[0]}, {r1[1]}}};')
        c.append('')
        h.append(f'extern const gfx_font_t gfx_font_{name};   /* height {H} px */')
    h += ['', '#ifdef __cplusplus', '}', '#endif', '', '#endif /* GFX_FONTS_H_ */', '']
    open(os.path.join(out,'gfx_fonts.c'),'w',encoding='utf-8',newline='\n').write('\n'.join(c))
    open(os.path.join(out,'gfx_fonts.h'),'w',encoding='utf-8',newline='\n').write('\n'.join(h))
    print('fonts: about %d bytes of flash in total' % total)

if __name__ == '__main__':
    if len(sys.argv) > 2:
        DJ = sys.argv[2].rstrip('/\\') + '/'
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
